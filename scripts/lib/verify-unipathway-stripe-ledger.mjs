import assert from 'node:assert/strict';
export async function verifyStripeLedger(db) {
 const id=n=>`50000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const tenant=id(1), other=id(2), student=id(3), invoice=id(4), drift=id(5);
 let checks=0;
 const ok=(v,m)=>{assert.ok(v,m);checks++;};
 const denied=async fn=>{await db.exec('SAVEPOINT denied');await assert.rejects(fn);await db.exec('ROLLBACK TO SAVEPOINT denied');checks++;};
 const args=['evt_first','pi_first',invoice,tenant,student,2500,'pkr',false];
 const pay=(values=args)=>db.query('select public.record_unipathway_stripe_payment($1,$2,$3,$4,$5,$6,$7,$8) result',values);
 const count=async table=>(await db.query(`select count(*)::int n from public.${table}`)).rows[0].n;
 await db.exec('BEGIN');
 await db.query("insert into public.tenants(id,name,slug) values($1,'Payment QA','unipathway'),($2,'Other','payment-qa-other')",[tenant,other]);
 await db.query("insert into auth.users(id,email,email_confirmed_at) values($1,'payments@example.invalid',now())",[student]);
 await db.query("insert into public.invoices(id,tenant_id,student_id,student_name,amount,paid,status) values($1,$2,$3,'QA',100,0,'pending'),($4,$2,$3,'Drift',100,10,'partial')",[invoice,tenant,student,drift]);
 const initialNotifications=await count('notifications'), initialAudit=await count('audit_logs');
 await db.exec('SET LOCAL ROLE authenticated'); await denied(()=>pay());
 await denied(()=>db.query('select * from public.unipathway_stripe_receipts'));
 await db.exec('RESET ROLE;SET LOCAL ROLE anon');await denied(()=>pay());
 await db.exec('RESET ROLE;SET LOCAL ROLE service_role');
 for(const values of [args.map((v,i)=>i===3?other:v),args.map((v,i)=>i===4?id(9):v),args.map((v,i)=>i===6?'gbp':v),args.map((v,i)=>i===5?0:v),args.map((v,i)=>i===2?drift:v)]) await denied(()=>pay(values));
 ok((await pay()).rows[0].result.status==='recorded','First payment recorded');
 ok((await db.query('select paid,status from public.invoices where id=$1',[invoice])).rows[0].paid==='25.00','Partial balance recorded by real historical triggers');
 ok((await db.query('select status from public.invoices where id=$1',[invoice])).rows[0].status==='partial','Not marked fully paid');
 ok((await pay()).rows[0].result.status==='duplicate','Same event deduplicates');
 ok((await pay(args.map((v,i)=>i===0?'evt_redelivery':v))).rows[0].result.status==='duplicate','Different event same intent deduplicates');
 await denied(()=>pay(args.map((v,i)=>i===5?2600:v)));
 await denied(()=>pay(args.map((v,i)=>i===1?'pi_reusedEvent':v)));
 await denied(()=>pay(['evt_excess','pi_excess',invoice,tenant,student,7600,'pkr',false]));
 await db.exec('RESET ROLE');
 ok(await count('payments')===1,'Duplicates and denied writes create no payment');
 ok(await count('notifications')===initialNotifications+1,'Exactly one receipt notice');
 ok(await count('audit_logs')===initialAudit+1,'Exactly one ledger audit');
 // Simulate a downstream storage failure: every preceding write must roll back.
 await db.exec("CREATE FUNCTION public.qa_fail_payment_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'simulated audit failure'; END; $$; CREATE TRIGGER qa_fail_payment_audit BEFORE INSERT ON public.audit_logs FOR EACH ROW EXECUTE FUNCTION public.qa_fail_payment_audit();SET LOCAL ROLE service_role");
 await denied(()=>pay(['evt_second','pi_second',invoice,tenant,student,7500,'pkr',false]));
 await db.exec('RESET ROLE');
 ok(await count('payments')===1 && await count('unipathway_stripe_receipts')===1,'Atomic rollback includes ledger and dedup receipt');
 ok((await db.query('select paid from public.invoices where id=$1',[invoice])).rows[0].paid==='25.00','Atomic rollback preserves balance');
 ok(await count('notifications')===initialNotifications+1,'Atomic rollback removes notice');
 await db.exec('DROP TRIGGER qa_fail_payment_audit ON public.audit_logs;SET LOCAL ROLE service_role');
 ok((await pay(['evt_second','pi_second',invoice,tenant,student,7500,'pkr',false])).rows[0].result.status==='recorded','Failed event can retry successfully');
 const final=(await db.query('select paid,status from public.invoices where id=$1',[invoice])).rows[0];
 ok(final.paid==='100.00'&&final.status==='paid','Payments accumulate to fully paid');
 await denied(()=>pay(['evt_third','pi_third',invoice,tenant,student,100,'pkr',false]));
 await db.exec('RESET ROLE');await db.query("update public.invoices set status='refunded' where id=$1",[invoice]);
 await db.exec('SET LOCAL ROLE service_role');
 ok((await pay()).rows[0].result.status==='duplicate','Old success retry cannot undo refund status');
 ok((await db.query('select status from public.invoices where id=$1',[invoice])).rows[0].status==='refunded','Refund state preserved');
 await db.exec('ROLLBACK');
 console.log(JSON.stringify({stripeLedgerFullSchemaChecks:checks,status:'passed'}));
}
