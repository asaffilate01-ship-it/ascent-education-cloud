import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const db=new PGlite();
const tenant='10000000-0000-4000-8000-000000000001';
const approved='20000000-0000-4000-8000-000000000001',other='20000000-0000-4000-8000-000000000002',external='20000000-0000-4000-8000-000000000003';
const session='30000000-0000-4000-8000-000000000001';
const q=sql=>db.query(sql);
await db.exec(`
 CREATE ROLE authenticated; CREATE ROLE anon; CREATE ROLE supabase_auth_admin;
 CREATE SCHEMA auth;
 CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE SET search_path='' AS $$SELECT coalesce(nullif(current_setting('test.jwt',true),''),'{}')::jsonb$$;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE SET search_path='' AS $$SELECT (auth.jwt()->>'sub')::uuid$$;
 GRANT USAGE ON SCHEMA auth TO authenticated,anon;
 CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,email_confirmed_at timestamptz);
 CREATE TABLE auth.sessions(id uuid PRIMARY KEY,user_id uuid,created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now(),ip inet,user_agent text,aal text,not_after timestamptz);
 CREATE TABLE public.tenants(id uuid PRIMARY KEY,status text);
 CREATE TABLE public.profiles(user_id uuid PRIMARY KEY,tenant_id uuid);
 CREATE TABLE public.user_roles(user_id uuid,tenant_id uuid,role text);
 CREATE TABLE public.test_records(id int PRIMARY KEY,tenant_id uuid);
 INSERT INTO public.tenants VALUES('${tenant}','active');
 INSERT INTO auth.users VALUES('${approved}','approved@unipathway.pk',now()),('${other}','other@unipathway.pk',now()),('${external}','external@example.com',now());
 INSERT INTO public.profiles VALUES('${approved}','${tenant}'),('${other}','${tenant}'),('${external}','${tenant}');
 INSERT INTO public.user_roles VALUES('${approved}','${tenant}','student'),('${other}','${tenant}','student'),('${external}','${tenant}','student');
 INSERT INTO auth.sessions(id,user_id,ip,aal) VALUES('${session}','${approved}','192.0.2.10','aal2');
 INSERT INTO public.test_records VALUES(1,'${tenant}');
 ALTER TABLE public.tenants ENABLE ROW LEVEL SECURITY;
 ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
 ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;
 ALTER TABLE public.test_records ENABLE ROW LEVEL SECURITY;
 CREATE POLICY test_read ON public.test_records FOR SELECT TO authenticated USING(true);
 GRANT SELECT ON public.test_records TO authenticated;
`);
await db.exec(readFileSync('scripts/activation/unipathway-institutional-auth-forward.sql','utf8'));
await db.exec(`INSERT INTO unipathway_identity.approved_accounts(user_id,approved_email,approval_reference) VALUES('${approved}','approved@unipathway.pk','Synthetic approval')`);
await db.exec(readFileSync('scripts/activation/unipathway-institutional-rls-forward.sql','utf8'));
const claims={sub:approved,email:'approved@unipathway.pk',aal:'aal2',is_anonymous:false,session_id:session};
async function as(role,token,sql){
 await db.exec('RESET ROLE');
 await db.query("SELECT set_config('test.jwt',$1,false)",[JSON.stringify(token)]);
 await db.exec('SET ROLE '+role);
 try{return await q(sql);}finally{await db.exec('RESET ROLE');}
}
const allowed=async token=>(await as('authenticated',token,'SELECT public.unipathway_institutional_access() AS ok')).rows[0].ok;
assert.equal(await allowed(claims),true);
assert.equal(await allowed({...claims,aal:'aal1'}),false);
assert.equal(await allowed({...claims,session_id:'30000000-0000-4000-8000-000000000099'}),false);
assert.equal(await allowed({...claims,is_anonymous:true}),false);
assert.equal(await allowed({...claims,email:'external@example.com'}),false);
assert.equal(await allowed({...claims,sub:other,email:'other@unipathway.pk'}),false);
assert.equal((await as('authenticated',claims,'SELECT * FROM public.test_records')).rows.length,1);
assert.equal((await as('authenticated',{...claims,aal:'aal1'},'SELECT * FROM public.test_records')).rows.length,0);
await assert.rejects(()=>as('authenticated',claims,'SELECT * FROM unipathway_identity.current_login_sessions'),/permission denied/i);
await assert.rejects(()=>as('authenticated',claims,'UPDATE unipathway_identity.approved_accounts SET revoked_at=NULL'),/permission denied/i);
await assert.rejects(()=>as('anon',{},'SELECT public.unipathway_institutional_access()'),/permission denied/i);
const hook=user=>`SELECT unipathway_identity.institutional_token_hook('${JSON.stringify({user_id:user,claims:{email:user===approved?'approved@unipathway.pk':'other@unipathway.pk',is_anonymous:false,aal:'aal1'}})}'::jsonb)`;
await as('supabase_auth_admin',{},hook(approved));
await assert.rejects(()=>as('supabase_auth_admin',{},hook(other)),/not authorised/i);
await assert.rejects(()=>as('authenticated',claims,hook(approved)),/permission denied/i);
assert.equal((await q('SELECT ip::text AS ip FROM unipathway_identity.current_login_sessions')).rows.length,1);
await q(`UPDATE public.tenants SET status='suspended' WHERE id='${tenant}'`);
assert.equal(await allowed(claims),false);
await q(`UPDATE public.tenants SET status='active' WHERE id='${tenant}'`);
await q(`UPDATE unipathway_identity.approved_accounts SET revoked_at=now() WHERE user_id='${approved}'`);
assert.equal(await allowed(claims),false);
await q(`UPDATE unipathway_identity.approved_accounts SET revoked_at=NULL WHERE user_id='${approved}'`);
await q(`DELETE FROM auth.sessions WHERE id='${session}'`);
assert.equal(await allowed(claims),false);
await db.close();
console.log('Institutional auth synthetic rehearsal passed; no hosted acceptance implied.');
