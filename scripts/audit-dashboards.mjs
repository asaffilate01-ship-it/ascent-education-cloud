import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const app = fs.readFileSync('src/App.tsx', 'utf8');
const routes = [...app.matchAll(/<Route path="([^"]+)" element=\{([^\n]+?)\} \/>/g)].map(m => ({route: m[1], components: [...m[2].matchAll(/<([A-Z]\w*)/g)].map(x => x[1])}));
const imports = new Map([...app.matchAll(/import (\w+) from ['"]([^'"]+)['"]/g)].map(m => [m[1], m[2].replace(/^@\//, 'src/') + '.tsx']));
for (const match of app.matchAll(/const\s+(\w+)\s*=\s*lazy\(\s*\(\)\s*=>\s*import\(['"]([^'"]+)['"]\)/g)) {
 imports.set(match[1], path.posix.normalize(match[2].replace(/^@\//, 'src/').replace(/^\.\//, 'src/') + '.tsx'));
}
const auth = fs.readFileSync('src/contexts/AuthContext.tsx', 'utf8');
const homes = [...auth.slice(auth.indexOf('export const ROLE_HOME:'), auth.indexOf('async function fetchAuthUser')).matchAll(/(\w+):\s*'([^']+)'/g)];
const candidates = [];
const files = [];
function walk(dir) {for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {const file = path.join(dir, entry.name);if (entry.isDirectory()) walk(file); else if (file.endsWith('.tsx')) files.push(file);}}
walk('src/pages');
for (const file of files) {
 const source = fs.readFileSync(file, 'utf8');
 const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
 function visit(node) {
  if (ts.isJsxElement(node)) {
   const open = node.openingElement;
   if (['Button', 'button'].includes(open.tagName.getText(ast))) {
    const props = open.attributes.properties;
    const names = props.filter(ts.isJsxAttribute).map(p => p.name.getText(ast));
    const text = node.getText(ast);
    const submit = props.some(p => ts.isJsxAttribute(p) && p.name.getText(ast) === 'type' && p.initializer?.getText(ast) === '"submit"');
    if (!names.some(n => ['onClick', 'asChild', 'disabled'].includes(n)) && !props.some(ts.isJsxSpreadAttribute) && !submit && !/onClick=/.test(text)) {
      const label = node.children.filter(ts.isJsxText).map(c => c.text.trim()).filter(Boolean).join(' ').replace(/\|/g, '/');
      candidates.push({file, line: ast.getLineAndCharacterOfPosition(node.getStart()).line + 1, label: label || '(icon or dynamic label)'});
    }
   }
  }
  ts.forEachChild(node, visit);
 }
 visit(ast);
}
const grouped = new Map();
for (const r of routes) {const page = r.components.at(-1);if (!grouped.has(page)) grouped.set(page, []);grouped.get(page).push(r.route);}
const lines = ['# Dashboard and route source inventory', '', 'Generated by `npm run audit:dashboards`. This is static source evidence, not a browser or authorization test. Shared route components can be intentional; rows require checking for route-aware behaviour. Button candidates may be wired by a parent dialog/form and require manual review.', '', `Inspected ${files.length} page files and ${routes.length} literal route declarations; ${candidates.length} button candidates need review.`, '', '## Role home coverage', '', '| Role | Home | Source |', '|---|---|---|'];
for (const [, role, home] of homes) {
 const route = routes.find(r => r.route === home);
 const source = route && imports.get(route.components.at(-1));
 if (!source || !fs.existsSync(source)) throw new Error(`Unresolved role home: ${role} (${home})`);
 lines.push(`| ${role} | ${home} | ${source} |`);
}
lines.push('', '## Route mapping', '', '| Route | Guard/wrapper | Page | Source |', '|---|---|---|---|');
for (const r of routes) lines.push(`| ${r.route} | ${r.components.slice(0, -1).join(', ') || 'None shown'} | ${r.components.at(-1)} | ${imports.get(r.components.at(-1)) || 'Inline/other'} |`);
lines.push('', '## Pages reused by multiple routes', '', '| Page | Routes |', '|---|---|');
for (const [page, list] of grouped) if (list.length > 1) lines.push(`| ${page} | ${list.join(', ')} |`);
lines.push('', '## Button candidates for manual review', '', '| Source | Line | Label |', '|---|---|---|');
for (const c of candidates) lines.push(`| ${c.file} | ${c.line} | ${c.label} |`);
fs.writeFileSync('docs/UNIPATHWAY_DASHBOARD_INVENTORY.md', lines.join('\n') + '\n');
console.log(`${files.length} pages, ${routes.length} literal routes, ${candidates.length} button candidates`);
